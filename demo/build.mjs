// Builds the demo vault from scratch: TaskNotes + this plugin, made-up tasks dated relative to today.
//   node demo/build.mjs            (reset.sh calls this)
// DEMO_VAULT overrides the location. The script only ever deletes a folder it created itself (it carries .tnc-demo).
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const vault = process.env.DEMO_VAULT || path.join(homedir(), 'Obsidian', 'TaskNotes-Countdown-Demo');
const marker = path.join(vault, '.tnc-demo');

if (existsSync(vault) && !existsSync(marker)) {
	console.error(`${vault} exists but is not a demo vault (no .tnc-demo). Not touching it.`);
	process.exit(1);
}
for (const f of ['main.js', 'manifest.json', 'styles.css']) {
	if (!existsSync(path.join(repo, f))) { console.error(`Missing ${f}. Run npm run build first.`); process.exit(1); }
	if (!existsSync(path.join(repo, 'demo/.cache/tasknotes', f))) { console.error(`Missing TaskNotes ${f}. Run demo/reset.sh, which downloads it.`); process.exit(1); }
}
rmSync(vault, { recursive: true, force: true });
mkdirSync(vault, { recursive: true });
writeFileSync(marker, 'Generated by demo/build.mjs. reset.sh deletes and rebuilds this folder.\n');

const write = (rel, text) => {
	const p = path.join(vault, rel);
	mkdirSync(path.dirname(p), { recursive: true });
	writeFileSync(p, text);
};
const json = (rel, obj) => write(rel, JSON.stringify(obj, null, 2) + '\n');

const today = new Date();
const day = n => {
	const d = new Date(today.getFullYear(), today.getMonth(), today.getDate() + n);
	return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
};

// Made-up tasks: exams, applications and a few ordinary ones, in English, Chinese and Japanese.
const tasks = [
	{ title: 'Mock exam - statistics', due: day(0), tags: ['exam'], priority: 'high' },
	{ title: 'Scholarship essay final draft', due: day(1), tags: ['application'], priority: 'high' },
	{ title: 'Buy printer ink', due: day(2), tags: [], priority: 'low' },
	{ title: '提交研究计划书', due: day(3), tags: ['application'], priority: 'high' },
	{ title: 'Graduate portal closes', due: `${day(5)}T17:00`, tags: ['application'], priority: 'high' },
	{ title: 'TOEFL iBT', due: day(12), tags: ['exam'], priority: 'normal' },
	{ title: '日本語能力試験 N1', due: day(30), tags: ['exam'], priority: 'normal' },
	{ title: 'Portfolio review with advisor', due: day(45), tags: ['application'], priority: 'normal' },
	{ title: 'Visa documents ready', due: day(70), tags: ['application'], priority: 'normal' },
	{ title: 'Ask for recommendation letter', due: day(-2), tags: ['application'], priority: 'high' },
	{ title: 'Transcript translation', due: day(-1), tags: ['application'], status: 'done' },
	{ title: 'Old practice test', due: day(-20), tags: ['exam', 'archived'] },
	{ title: 'Read methods paper', tags: [] },
];
for (const t of tasks) {
	const fm = ['---', `title: ${JSON.stringify(t.title)}`, `status: ${t.status ?? 'open'}`, `priority: ${t.priority ?? 'normal'}`];
	if (t.due) fm.push(`due: ${t.due}`);
	fm.push('tags:', ...['task', ...t.tags].map(tag => `  - ${tag}`), `dateCreated: ${day(-30)}T09:00:00.000+00:00`, '---', '');
	const safe = t.title.replace(/[\\/:*?"<>|]/g, '-');
	write(`TaskNotes/Tasks/${safe}.md`, fm.join('\n') + 'Made-up demo task.\n');
}

write('TaskNotes/Views/Countdown.base', [
	'filters:', '  and:', '    - "file.hasTag(\\"task\\")"', '    - "!note[\\"due\\"].isEmpty()"',
	'views:', '  - type: tasknotes-countdown', '    name: "Countdown"', '    order:', '      - file.name', '      - note.due',
	'    sort:', '      - property: note.due', '        direction: ASC', '    dateProperty: note.due', '    statusProperty: note.status', '',
].join('\n'));

write('Home.md', `# TaskNotes Countdown demo

Everything here is made up. Dates move with today each time the vault is reset.

1. Open **TaskNotes/Views/Countdown.base**. The nearest deadline is large; the rest is grouped by how close it is.
2. Open the sidebar card with the hourglass in the ribbon. It shows only tasks tagged \`exam\` or \`application\` (Settings → TaskNotes Countdown).
3. Change a task's due date or mark it done in TaskNotes. Both views update on their own.
`);

// Obsidian config: Bases on, the two plugins on, nothing else.
const cfg = '.obsidian';
json(`${cfg}/app.json`, { alwaysUpdateLinks: true, promptDelete: true, livePreview: true, showUnsupportedFiles: false });
json(`${cfg}/appearance.json`, { theme: 'system', cssTheme: '', enabledCssSnippets: [], accentColor: '' });
json(`${cfg}/core-plugins.json`, {
	'file-explorer': true, 'global-search': true, switcher: true, 'command-palette': true, 'tag-pane': true,
	properties: true, 'page-preview': true, bases: true, outline: true, backlink: false, 'outgoing-link': false,
	graph: false, canvas: false, 'daily-notes': false, templates: false, 'note-composer': false, 'file-recovery': false,
	'random-note': false, 'slash-command': false, 'markdown-importer': false, 'zk-prefixer': false, slides: false,
	'audio-recorder': false, workspaces: false, publish: false, sync: false, webviewer: false, footnotes: false, bookmarks: false,
});
json(`${cfg}/community-plugins.json`, ['tasknotes', 'tasknotes-countdown']);
for (const f of ['main.js', 'manifest.json', 'styles.css']) {
	mkdirSync(path.join(vault, cfg, 'plugins/tasknotes'), { recursive: true });
	mkdirSync(path.join(vault, cfg, 'plugins/tasknotes-countdown'), { recursive: true });
	cpSync(path.join(repo, 'demo/.cache/tasknotes', f), path.join(vault, cfg, 'plugins/tasknotes', f));
	cpSync(path.join(repo, f), path.join(vault, cfg, 'plugins/tasknotes-countdown', f));
}
json(`${cfg}/plugins/tasknotes-countdown/data.json`, { tags: 'exam, application', limit: 6, urgentDays: 3 });
json(`${cfg}/workspace.json`, {
	main: { id: 'm0', type: 'split', direction: 'vertical', children: [{ id: 'm1', type: 'tabs', children: [
		{ id: 'm2', type: 'leaf', state: { type: 'markdown', state: { file: 'Home.md', mode: 'preview' } } }] }] },
	left: { id: 'l0', type: 'split', direction: 'horizontal', width: 260, children: [{ id: 'l1', type: 'tabs', children: [
		{ id: 'l2', type: 'leaf', state: { type: 'file-explorer', state: {} } }] }] },
	right: { id: 'r0', type: 'split', direction: 'horizontal', width: 340, children: [{ id: 'r1', type: 'tabs', children: [
		{ id: 'r2', type: 'leaf', state: { type: 'tasknotes-countdown-sidebar', state: {} } }] }] },
	active: 'm2', lastOpenFiles: ['Home.md'],
});
console.log(`Demo vault ready: ${vault} (${tasks.length} tasks)`);
